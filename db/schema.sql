-- Purpose: create the application's outing_records table in the public schema.
-- This file does not create a database, schema, or modify existing objects.
-- Run only after confirming that weather_travel_db is the intended target.

CREATE TABLE IF NOT EXISTS public.outing_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outing_date DATE NOT NULL,
    city VARCHAR(100) NOT NULL,
    destination VARCHAR(200) NOT NULL,
    activity TEXT,
    notes TEXT,
    weather VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT outing_records_city_not_blank
        CHECK (char_length(btrim(city)) > 0),
    CONSTRAINT outing_records_destination_not_blank
        CHECK (char_length(btrim(destination)) > 0),
    CONSTRAINT outing_records_activity_length
        CHECK (activity IS NULL OR char_length(activity) <= 5000),
    CONSTRAINT outing_records_notes_length
        CHECK (notes IS NULL OR char_length(notes) <= 5000)
);

CREATE INDEX IF NOT EXISTS outing_records_date_id_desc_idx
    ON public.outing_records (outing_date DESC, id DESC);
