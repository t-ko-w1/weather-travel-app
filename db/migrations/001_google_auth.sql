-- Apply to weather_travel_db after verifying the target database.
-- Adds auth objects without deleting or rewriting existing outing records.
BEGIN;

CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_sub VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(320) NOT NULL,
    email_verified BOOLEAN NOT NULL,
    display_name VARCHAR(200),
    avatar_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_email_not_blank CHECK (char_length(btrim(email)) > 0)
);

ALTER TABLE public.outing_records
    ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES public.users(id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS outing_records_user_date_id_desc_idx
    ON public.outing_records (user_id, outing_date DESC, id DESC);

CREATE TABLE IF NOT EXISTS public.user_sessions (
    sid VARCHAR NOT NULL PRIMARY KEY,
    sess JSON NOT NULL,
    expire TIMESTAMP(6) NOT NULL
);

CREATE INDEX IF NOT EXISTS user_sessions_expire_idx
    ON public.user_sessions (expire);

COMMIT;
