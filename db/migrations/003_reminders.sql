-- Apply to weather_travel_db after confirming the target database and backup.
-- Adds reminder settings and delivery history without deleting or reassigning trips.
BEGIN;

ALTER TABLE public.outing_records
    ADD COLUMN IF NOT EXISTS reminder_enabled BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS public.reminder_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outing_record_id BIGINT UNIQUE REFERENCES public.outing_records(id) ON DELETE SET NULL,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    outing_date DATE NOT NULL,
    destination_snapshot VARCHAR(200) NOT NULL,
    scheduled_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    attempt_count SMALLINT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ,
    lock_expires_at TIMESTAMPTZ,
    recipient_email VARCHAR(320),
    sent_at TIMESTAMPTZ,
    last_error_code VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT reminder_jobs_status CHECK (status IN ('pending', 'retry_wait', 'processing', 'sent', 'cancelled', 'missed', 'failed')),
    CONSTRAINT reminder_jobs_attempt_count CHECK (attempt_count BETWEEN 0 AND 5),
    CONSTRAINT reminder_jobs_destination_not_blank CHECK (char_length(btrim(destination_snapshot)) > 0),
    CONSTRAINT reminder_jobs_lock_state CHECK ((status = 'processing') = (lock_expires_at IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS reminder_jobs_due_idx
    ON public.reminder_jobs (scheduled_at, next_attempt_at, id)
    WHERE status IN ('pending', 'retry_wait');

CREATE INDEX IF NOT EXISTS reminder_jobs_lease_idx
    ON public.reminder_jobs (lock_expires_at, id)
    WHERE status = 'processing';

CREATE TABLE IF NOT EXISTS public.reminder_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reminder_job_id BIGINT NOT NULL REFERENCES public.reminder_jobs(id) ON DELETE RESTRICT,
    attempt_number SMALLINT NOT NULL,
    status VARCHAR(12) NOT NULL,
    recipient_email VARCHAR(320) NOT NULL,
    provider_message_id VARCHAR(255),
    error_code VARCHAR(100),
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,

    CONSTRAINT reminder_attempts_number CHECK (attempt_number BETWEEN 1 AND 5),
    CONSTRAINT reminder_attempts_status CHECK (status IN ('started', 'sent', 'failed', 'unknown')),
    CONSTRAINT reminder_attempts_job_number UNIQUE (reminder_job_id, attempt_number)
);

COMMIT;
